"""What the refresh needs from the outside world; tarkon/adapters holds the real ones, the tests hold fakes."""

from typing import Protocol


class Tickets(Protocol):
    def fetch_epics(self, settings): ...
    def fetch_children(self, epic_key): ...
    def fetch_updated(self, key): ...
    def changed_since(self, keys, minutes, linked_to=()): ...
    def fetch_my_tickets(self, details): ...
    def fetch_ticket_detail(self, key): ...


class PullRequests(Protocol):
    def search_terms(self, keys): ...
    def search_prs(self, query): ...
    def fetch_prs(self, candidates): ...
    def fetch_pr_states(self, urls): ...


class Store(Protocol):
    """Json-shaped data kept under a name: what was written reads back as plain dicts and lists, or None when missing."""

    def read(self, name): ...
    def write(self, name, data): ...


class Clock(Protocol):
    def time(self): ...
    def now(self): ...
